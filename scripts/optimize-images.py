#!/usr/bin/env python3
"""Re-encode *new* source WebP images at maximum compression effort, once.

WebP's `-m` flag (0-6) is the encoder's *effort* level, not its quality: at a
fixed fidelity, a higher method searches harder for a more compact packing of
the same pixels. Images exported by other tools usually come at the fast
default (method 4) or from a less efficient encoder, leaving bytes on the table.

Every lossy re-encode costs one generation of quality, so the script touches an
image **once**, when it arrives, and never again:

  * Only *new* images are candidates — WebPs under images/ that git sees as
    untracked or modified. Committed, unchanged images were optimized when they
    arrived and are skipped. (@cards/ is generated by generate-thumbnails.py and
    @icons/ is a fixed set; both are always excluded.)
  * A file this script wrote is remembered by content hash in
    scripts/.optimized-images.json (git-ignored), so a second run before the
    commit skips it too. The pass is idempotent.

Fidelity is **measured, not trusted**. cwebp's own `-psnr` target scores in its
internal YUV space and lands 2–7 dB under the requested value once the result is
decoded back to RGB. Instead this binary-searches cwebp's `-q` at method 6 +
`-sharp_yuv` for the smallest file whose decoded pixels reach PSNR_TARGET dB
against the input's, measured here in RGB(A). A lossless method-6 encode is also
tried; the smaller passing candidate wins, and replaces the original only when
it is smaller by a meaningful margin (MIN_SAVING_PCT and MIN_SAVING_BYTES).
No image is made bigger or brought below the target.

What to expect: a lossless export (PNG-like WebP) usually shrinks; an image that
arrives already lossy usually stays as it is, because honest 50 dB costs more
bytes than the file already has. The old version's savings on such files were
mostly quality loss.

Requires libwebp's `cwebp` on PATH (brew install webp). Run from the repo root:

    uv run scripts/optimize-images.py                    # every new image
    uv run scripts/optimize-images.py images/<slug>/     # narrow to paths
    uv run scripts/optimize-images.py --dry-run          # report only

`--force` re-optimizes named files even when committed or already optimized —
it costs them another generation, so use it only on a file you know is fresh.

Then run scripts/generate-thumbnails.py, which builds the homepage cards from
these sources.
"""

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

METHOD = 6               # max compression effort (0=fast … 6=slowest); quality-neutral
PSNR_TARGET = 50.0       # dB in RGB(A) vs the input's pixels — strict visually lossless
MIN_SAVING_PCT = 5.0     # only replace when at least this much smaller …
MIN_SAVING_BYTES = 2048  # … and at least this many bytes, to skip trivial churn

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "images"
EXCLUDE_DIRS = {"@cards", "@icons"}
CACHE = ROOT / "scripts" / ".optimized-images.json"


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def excluded(path):
    return any(part in EXCLUDE_DIRS for part in path.relative_to(IMAGES).parts)


def git_new():
    """Repo-relative paths of WebPs under images/ that are untracked or modified."""
    out = subprocess.run(
        ["git", "status", "--porcelain", "-z", "--untracked-files=all", "--", "images"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    paths = set()
    entries = iter(out.split("\0"))
    for entry in entries:
        if not entry:
            continue
        status, path = entry[:2], entry[3:]
        if status[0] in "RC":
            next(entries, None)  # a rename carries its old path as the next entry
        if "D" not in status and path.endswith(".webp"):
            paths.add((ROOT / path).resolve())
    return paths


def expand(args):
    """WebPs named on the command line, files or directories, resolved."""
    found = []
    for arg in args:
        path = Path(arg).resolve()
        if path.is_dir():
            found.extend(sorted(path.rglob("*.webp")))
        elif path.suffix == ".webp" and path.is_file():
            found.append(path)
        else:
            sys.exit(f"not a WebP file or directory: {arg}")
    for path in found:
        if not path.is_relative_to(IMAGES):
            sys.exit(f"outside images/: {path}")
    return found


def pixels(path):
    """Decoded pixels as float RGB, or RGBA with colour zeroed where fully transparent
    (cwebp may rewrite the invisible colour under alpha = 0, which is not a loss)."""
    with Image.open(path) as im:
        alpha = "A" in im.getbands()
        px = np.asarray(im.convert("RGBA" if alpha else "RGB"), dtype=np.float64)
    if alpha:
        px[px[..., 3] == 0, :3] = 0
    return px


def psnr(a, b):
    mse = np.mean((a - b) ** 2)
    return float("inf") if mse == 0 else 10 * np.log10(255 ** 2 / mse)


def encode(src, dst, *opts):
    """cwebp at method 6; returns the size, or None if the encode failed."""
    result = subprocess.run(
        ["cwebp", "-quiet", "-m", str(METHOD), "-metadata", "none", *opts,
         str(src), "-o", str(dst)],
        capture_output=True,
    )
    ok = result.returncode == 0 and dst.is_file() and dst.stat().st_size > 0
    return dst.stat().st_size if ok else None


def best_encode(src, tmp):
    """Smallest method-6 encode of src at or above PSNR_TARGET, as (path, size, dB, how).
    None when no candidate passes or cwebp fails."""
    ref = pixels(src)
    candidates = []

    lossless = tmp / "lossless.webp"
    if encode(src, lossless, "-lossless", "-z", "9", "-exact"):
        candidates.append((lossless, lossless.stat().st_size, psnr(ref, pixels(lossless)), "lossless"))

    # Smallest -q that reaches the target; PSNR rises with q, so bisect. Lossy WebP
    # is always 4:2:0, which caps a detailed colour image's PSNR below the target
    # even at q100 (43.7 dB on one photo); in that case only lossless can pass.
    lo, hi, found = 0, 100, None
    ceiling = tmp / "q100.webp"
    if not encode(src, ceiling, "-q", "100", "-sharp_yuv", "-alpha_q", "100"):
        return None
    if psnr(ref, pixels(ceiling)) < PSNR_TARGET:
        lo = hi + 1  # skip the search
    while lo <= hi:
        q = (lo + hi) // 2
        trial = tmp / f"q{q}.webp"
        if not encode(src, trial, "-q", str(q), "-sharp_yuv", "-alpha_q", "100"):
            return None
        db = psnr(ref, pixels(trial))
        if db >= PSNR_TARGET:
            found, hi = (trial, trial.stat().st_size, db, f"q{q}"), q - 1
        else:
            lo = q + 1
    if found:
        candidates.append(found)

    passing = [c for c in candidates if c[2] >= PSNR_TARGET]
    return min(passing, key=lambda c: c[1]) if passing else None


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("paths", nargs="*",
                        help="WebP files or directories under images/ (default: all new images)")
    parser.add_argument("--dry-run", action="store_true",
                        help="report savings without modifying any file")
    parser.add_argument("--force", action="store_true",
                        help="also re-optimize named files that are committed or already optimized")
    args = parser.parse_args()
    if args.force and not args.paths:
        parser.error("--force needs explicit paths; it never applies to the whole corpus")

    cache = set(json.loads(CACHE.read_text())) if CACHE.exists() else set()
    new = git_new()
    named = expand(args.paths) if args.paths else sorted(new)

    todo, skipped = [], 0
    for path in named:
        if excluded(path):
            continue
        if not args.force and (path not in new or sha256(path) in cache):
            skipped += 1
            continue
        todo.append(path)

    if not todo:
        print(f"Nothing to optimize ({skipped} already-optimized file(s) skipped).")
        return 0

    total_before = total_after = changed = failures = 0
    print(f"{'file':60} {'orig':>7} {'new':>7} {'dB':>5} {'how':>8} {'result':>7}")
    for src in todo:
        rel = str(src.relative_to(IMAGES))
        orig = src.stat().st_size
        with tempfile.TemporaryDirectory() as tmp:
            best = best_encode(src, Path(tmp))
            if best is None:
                print(f"{rel:60} {orig/1024:6.0f}K {'':>7} {'':>5} {'':>8} {'FAIL':>7}")
                failures += 1
                continue
            out, size, db, how = best
            saving = orig - size
            worth = saving >= MIN_SAVING_BYTES and saving >= orig * MIN_SAVING_PCT / 100
            total_before += orig
            total_after += size if worth else orig
            if worth:
                changed += 1
                if not args.dry_run:
                    out.replace(src)
            if not args.dry_run:
                cache.add(sha256(src))  # optimized, or checked and left as is
        shown = "∞" if db == float("inf") else f"{db:.1f}"
        label = f"-{saving * 100 // orig}%" if worth else "keep"
        print(f"{rel:60} {orig/1024:6.0f}K {size/1024:6.0f}K {shown:>5} {how:>8} {label:>7}")

    if not args.dry_run:
        CACHE.write_text(json.dumps(sorted(cache), indent=0) + "\n")

    saved = total_before - total_after
    print(f"\n{'DRY RUN: ' if args.dry_run else ''}"
          f"{changed} file(s) {'would be ' if args.dry_run else ''}re-encoded, "
          f"{skipped} skipped, {failures} failure(s)")
    if total_before:
        print(f"total: {total_before/1024:.0f} KB -> {total_after/1024:.0f} KB "
              f"(saved {saved/1024:.0f} KB, {saved * 100 // total_before}%)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
